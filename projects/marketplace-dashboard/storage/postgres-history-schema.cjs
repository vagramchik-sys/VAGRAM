'use strict';

module.exports = String.raw`
BEGIN;

CREATE SCHEMA IF NOT EXISTS pult_history;

CREATE TABLE IF NOT EXISTS pult_history.import_runs (
  run_id uuid PRIMARY KEY,
  source_fingerprint bytea,
  status text COLLATE "C" NOT NULL CHECK (status IN ('running', 'complete', 'failed')),
  started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
  completed_at timestamptz,
  table_counts jsonb NOT NULL DEFAULT '{}'::jsonb,
  table_hashes jsonb NOT NULL DEFAULT '{}'::jsonb,
  error_code text COLLATE "C",
  CHECK (source_fingerprint IS NULL OR octet_length(source_fingerprint) = 32),
  CHECK ((status = 'complete') = (completed_at IS NOT NULL))
);

CREATE TABLE IF NOT EXISTS pult_history.import_state (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  completed_run_id uuid NOT NULL REFERENCES pult_history.import_runs(run_id),
  source_fingerprint bytea NOT NULL CHECK (octet_length(source_fingerprint) = 32),
  table_counts jsonb NOT NULL,
  table_hashes jsonb NOT NULL,
  completed_at timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS pult_history.ingestions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_file text COLLATE "C" NOT NULL,
  content_hash text COLLATE "C" NOT NULL,
  captured_at timestamptz NOT NULL,
  captured_at_text text COLLATE "C" NOT NULL,
  source_kind text COLLATE "C" NOT NULL,
  UNIQUE (source_file, content_hash)
);

CREATE TABLE IF NOT EXISTS pult_history.snapshots (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingestion_id bigint NOT NULL REFERENCES pult_history.ingestions(id),
  source_kind text COLLATE "C" NOT NULL,
  market text COLLATE "C" NOT NULL,
  store_id text COLLATE "C" NOT NULL,
  day date NOT NULL,
  source_actual_at timestamptz NOT NULL,
  source_actual_at_text text COLLATE "C" NOT NULL,
  closed_confirmed boolean NOT NULL,
  partial_reason text,
  UNIQUE (ingestion_id, source_kind, store_id, day)
);

CREATE TABLE IF NOT EXISTS pult_history.facts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id bigint NOT NULL REFERENCES pult_history.snapshots(id),
  product_id text COLLATE "C" NOT NULL,
  observed_at timestamptz,
  observed_at_text text COLLATE "C",
  units double precision,
  revenue double precision,
  sold_units double precision,
  returned_units double precision,
  realized double precision,
  ads double precision,
  unknown_unit_rows bigint NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS pult_history.order_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id bigint NOT NULL REFERENCES pult_history.snapshots(id),
  product_id text COLLATE "C" NOT NULL,
  occurred_at timestamptz NOT NULL,
  occurred_at_text text COLLATE "C" NOT NULL,
  amount double precision
);

CREATE TABLE IF NOT EXISTS pult_history.product_names (
  market text COLLATE "C" NOT NULL,
  store_id text COLLATE "C" NOT NULL,
  product_id text COLLATE "C" NOT NULL,
  name text NOT NULL,
  source_actual_at timestamptz NOT NULL,
  source_actual_at_text text COLLATE "C" NOT NULL,
  PRIMARY KEY (market, store_id, product_id)
);

CREATE TABLE IF NOT EXISTS pult_history.product_aliases (
  market text COLLATE "C" NOT NULL,
  store_id text COLLATE "C" NOT NULL,
  alias text COLLATE "C" NOT NULL,
  product_id text COLLATE "C" NOT NULL,
  source_actual_at timestamptz NOT NULL,
  source_actual_at_text text COLLATE "C" NOT NULL,
  PRIMARY KEY (market, store_id, alias)
);

CREATE TABLE IF NOT EXISTS pult_history.archive_versions (
  source_file text COLLATE "C" NOT NULL,
  content_hash text COLLATE "C" NOT NULL,
  captured_at timestamptz NOT NULL,
  captured_at_text text COLLATE "C" NOT NULL,
  source_mtime double precision NOT NULL,
  source_bytes bigint NOT NULL CHECK (source_bytes >= 0),
  archive_bytes bigint NOT NULL CHECK (archive_bytes >= 0),
  object_path text COLLATE "C",
  facts_status text COLLATE "C" NOT NULL,
  archive_payload bytea NOT NULL,
  archive_gzip_hash bytea NOT NULL CHECK (octet_length(archive_gzip_hash) = 32),
  PRIMARY KEY (source_file, content_hash),
  CHECK (octet_length(archive_payload) = archive_bytes)
);

CREATE INDEX IF NOT EXISTS archive_versions_pending_facts_idx
  ON pult_history.archive_versions(captured_at, source_file, content_hash)
  WHERE facts_status = 'pending';

CREATE TABLE IF NOT EXISTS pult_history.archive_latest (
  source_file text COLLATE "C" PRIMARY KEY,
  stamp text COLLATE "C" NOT NULL,
  content_hash text COLLATE "C" NOT NULL,
  FOREIGN KEY (source_file, content_hash)
    REFERENCES pult_history.archive_versions(source_file, content_hash)
);

CREATE TABLE IF NOT EXISTS pult_history.archive_state (
  key text COLLATE "C" PRIMARY KEY,
  value text NOT NULL
);

CREATE TABLE IF NOT EXISTS pult_history.stock_imports (
  id text COLLATE "C" PRIMARY KEY,
  imported_at timestamptz NOT NULL,
  imported_at_text text COLLATE "C" NOT NULL,
  manifest jsonb NOT NULL,
  manifest_text text COLLATE "C" NOT NULL,
  issues jsonb NOT NULL,
  issues_text text COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS pult_history.stock_rows (
  id text COLLATE "C" PRIMARY KEY,
  day date NOT NULL,
  observed_at timestamptz,
  observed_at_text text COLLATE "C",
  source text COLLATE "C" NOT NULL,
  store_id text COLLATE "C" NOT NULL,
  store_name text NOT NULL,
  sku text COLLATE "C" NOT NULL,
  article text,
  name text,
  warehouse text,
  warehouse_id text COLLATE "C",
  cluster text,
  total_stock bigint,
  available bigint,
  in_transit bigint,
  reserved bigint,
  quality text,
  details jsonb NOT NULL,
  details_text text COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS pult_history.stock_origins (
  row_id text COLLATE "C" NOT NULL REFERENCES pult_history.stock_rows(id),
  import_id text COLLATE "C" NOT NULL REFERENCES pult_history.stock_imports(id),
  source_file text COLLATE "C" NOT NULL,
  source_row text COLLATE "C" NOT NULL,
  PRIMARY KEY (row_id, import_id, source_file, source_row)
);

CREATE INDEX IF NOT EXISTS snapshots_store_day_idx
  ON pult_history.snapshots(market, store_id, day, source_kind, closed_confirmed, source_actual_at DESC);
CREATE INDEX IF NOT EXISTS facts_product_snapshot_idx
  ON pult_history.facts(product_id, snapshot_id);
CREATE INDEX IF NOT EXISTS order_events_product_time_idx
  ON pult_history.order_events(product_id, occurred_at);
CREATE INDEX IF NOT EXISTS stock_scope_idx
  ON pult_history.stock_rows(source, store_id, day, sku);
CREATE INDEX IF NOT EXISTS stock_product_idx
  ON pult_history.stock_rows(store_id, sku, source, day);

COMMIT;
`;
